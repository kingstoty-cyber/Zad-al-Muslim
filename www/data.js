// نظام الذاكرة المحلية
const Storage = {
    save(key, data) { 
        try {
            localStorage.setItem(key, JSON.stringify(data)); 
        } catch (e) {
            console.error('خطأ في حفظ البيانات:', e);
        }
    },
    load(key) { 
        try {
            return JSON.parse(localStorage.getItem(key)) || null; 
        } catch (e) {
            console.error('خطأ في تحميل البيانات:', e);
            return null;
        }
    }
};

